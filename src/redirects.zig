//! Generated outputs that point elsewhere: redirect pages for frontmatter
//! `aliases`, a `_redirects` file for hosts that read one (Netlify,
//! Cloudflare Pages), and `robots.txt`.

const std = @import("std");
const Allocator = std.mem.Allocator;
const Writer = std.Io.Writer;
const escapeHtml = @import("markdown.zig").escapeHtml;

pub const redirects_path = "_redirects";
pub const robots_path = "robots.txt";

pub const Alias = struct {
    /// Old URL, including the baseurl, such as `/blog/old-post/`.
    from: []const u8,
    /// The page's URL, including the baseurl.
    to: []const u8,
};

/// An HTML page that sends browsers and crawlers from an old URL to `to`.
/// `canonical` is the target's absolute URL when the site URL is known,
/// else `to` itself. The page asks not to be indexed, so only the target
/// shows up in search results.
pub fn stub(arena: Allocator, to: []const u8, canonical: []const u8) Allocator.Error![]u8 {
    var aw: Writer.Allocating = .init(arena);
    writeStub(&aw.writer, to, canonical) catch return error.OutOfMemory;
    return aw.toOwnedSlice();
}

fn writeStub(w: *Writer, to: []const u8, canonical: []const u8) Writer.Error!void {
    try w.writeAll("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n<title>Redirecting…</title>\n");
    try w.writeAll("<link rel=\"canonical\" href=\"");
    try escapeHtml(w, canonical);
    try w.writeAll("\">\n<meta name=\"robots\" content=\"noindex\">\n<meta http-equiv=\"refresh\" content=\"0; url=");
    try escapeHtml(w, to);
    try w.writeAll("\">\n</head>\n<body>\n<p>This page has moved to <a href=\"");
    try escapeHtml(w, to);
    try w.writeAll("\">");
    try escapeHtml(w, to);
    try w.writeAll("</a>.</p>\n</body>\n</html>\n");
}

/// A `_redirects` file with one permanent redirect per alias.
pub fn redirectsFile(arena: Allocator, aliases: []const Alias) Allocator.Error![]u8 {
    var aw: Writer.Allocating = .init(arena);
    const w = &aw.writer;
    (blk: {
        w.writeAll("# Generated by Mortise from frontmatter aliases.\n") catch |e| break :blk e;
        for (aliases) |a| w.print("{s} {s} 301\n", .{ a.from, a.to }) catch |e| break :blk e;
    }) catch return error.OutOfMemory;
    return aw.toOwnedSlice();
}

/// A `robots.txt` that allows every crawler and, when given, names the
/// sitemap's absolute URL.
pub fn robots(arena: Allocator, sitemap_url: ?[]const u8) Allocator.Error![]u8 {
    if (sitemap_url) |u| return std.fmt.allocPrint(arena, "User-agent: *\nAllow: /\n\nSitemap: {s}\n", .{u});
    return arena.dupe(u8, "User-agent: *\nAllow: /\n");
}

/// Checks an alias from frontmatter: a root-relative path without spaces,
/// quotes, `?` or `#`. Returns an error message, or null when valid.
pub fn invalidAlias(a: []const u8) ?[]const u8 {
    if (a.len == 0 or a[0] != '/') return "each alias must be a path starting with '/'";
    if (std.mem.startsWith(u8, a, "//")) return "an alias must be a path on this site, not '//host'";
    for (a) |c| switch (c) {
        0...0x20, '"', '<', '>', '\\', '?', '#', 0x7f => return "an alias must not contain spaces, quotes, '?' or '#'",
        else => {},
    };
    return null;
}

const testing = std.testing;

test "stub redirects and asks not to be indexed" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();
    const out = try stub(arena.allocator(), "/blog/new/", "https://example.com/blog/new/");
    try testing.expectEqualStrings(
        \\<!DOCTYPE html>
        \\<html lang="en">
        \\<head>
        \\<meta charset="utf-8">
        \\<title>Redirecting…</title>
        \\<link rel="canonical" href="https://example.com/blog/new/">
        \\<meta name="robots" content="noindex">
        \\<meta http-equiv="refresh" content="0; url=/blog/new/">
        \\</head>
        \\<body>
        \\<p>This page has moved to <a href="/blog/new/">/blog/new/</a>.</p>
        \\</body>
        \\</html>
        \\
    , out);
}

test "redirects file and robots.txt" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    try testing.expectEqualStrings(
        "# Generated by Mortise from frontmatter aliases.\n/old/ /new/ 301\n/x.html /y/ 301\n",
        try redirectsFile(a, &.{ .{ .from = "/old/", .to = "/new/" }, .{ .from = "/x.html", .to = "/y/" } }),
    );
    try testing.expectEqualStrings("User-agent: *\nAllow: /\n\nSitemap: https://e.com/sitemap.xml\n", try robots(a, "https://e.com/sitemap.xml"));
    try testing.expectEqualStrings("User-agent: *\nAllow: /\n", try robots(a, null));
}

test "invalidAlias" {
    try testing.expect(invalidAlias("/old/") == null);
    try testing.expect(invalidAlias("/old.html") == null);
    try testing.expect(invalidAlias("old/") != null);
    try testing.expect(invalidAlias("//evil.com/") != null);
    try testing.expect(invalidAlias("/a b/") != null);
    try testing.expect(invalidAlias("/a?x=1") != null);
}
